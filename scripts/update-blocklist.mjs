// Refreshes the bundled list of disposable ("burner") email domains that
// signups are checked against. Redeploy afterwards so signups use the new list.
//   npm run update-blocklist
// Source: github.com/disposable-email-domains/disposable-email-domains (CC0 1.0).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE =
  "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";
const OUT = fileURLToPath(new URL("../src/data/disposable-domains.js", import.meta.url));

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`Couldn't fetch the list: HTTP ${res.status}`);
const domains = [
  ...new Set(
    (await res.text())
      .split(/\r?\n/)
      .map((l) => l.trim().toLowerCase())
      .filter((l) => l && !l.startsWith("#")),
  ),
].sort();

const bad = domains.filter((d) => !/^[a-z0-9.-]+\.[a-z0-9-]+$/.test(d));
if (bad.length) throw new Error(`Unexpected lines in the list, not saved: ${bad.slice(0, 5).join(", ")}`);
if (domains.length < 1000) throw new Error(`Only ${domains.length} domains - looks wrong, not saved`);

writeFileSync(
  OUT,
  `// Generated by scripts/update-blocklist.mjs - do not edit by hand.\n` +
    `// Disposable email domains from github.com/disposable-email-domains/disposable-email-domains\n` +
    `// (CC0 1.0, public domain), ${new Date().toISOString().slice(0, 10)}. ${domains.length} domains.\n` +
    `export const DISPOSABLE_DOMAINS = new Set(\`\n${domains.join("\n")}\n\`.trim().split("\\n"));\n`,
);
console.log(`Saved ${domains.length} domains to src/data/disposable-domains.js. Redeploy to use them.`);
